#!/bin/bash
# Builds proj6_submission.zip from code + results
cd "$(dirname "$0")"
cp -f REPORT.md FINAL_REPORT.md
{
  echo; echo "## 6. Results"; echo
  echo "### 6.1 Graph"; echo; echo "![Monitoring results](results.png)"; echo
  echo "### 6.2 Demo timeline (what was triggered, and when)"; echo '```'
  grep 'DEMO' results/demo_timeline.txt 2>/dev/null
  echo '```'; echo
  echo "### 6.3 Alerts generated by the monitor (alerts.log)"; echo '```'
  cat alerts.log 2>/dev/null; echo '```'; echo
  echo "### 6.4 Sample of the console dashboard (results/ryu_output.txt)"; echo '```'
  grep -A6 '^===' results/ryu_output.txt 2>/dev/null | head -60
  echo '```'
} >> FINAL_REPORT.md
command -v pandoc >/dev/null && pandoc FINAL_REPORT.md -o REPORT.docx --resource-path=. 2>/dev/null
rm -f proj6_submission.zip
zip -r proj6_submission.zip agent.py topo.py monitor_app.py relay.py demo.py plot.py setup.sh run_demo.sh run_manual.sh build_zip.sh \
    alerts.log metrics.csv results.png results FINAL_REPORT.md REPORT.docx README.txt 2>/dev/null
echo "=== DONE: $(pwd)/proj6_submission.zip ==="
